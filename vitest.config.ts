import { existsSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import react from "@vitejs/plugin-react";
import { parse } from "dotenv";
import { configDefaults, defineConfig } from "vitest/config";

const DATABASE_TESTS = "src/**/*.db.test.ts";
/** The Admin seam's suites, written over ADMIN_ARMS (test/admin-arms.ts). */
const ADMIN_SUITES = "src/services/admin.*.test.ts";
/** Admin tests that aren't written over ADMIN_ARMS. */
const NOT_ADMIN_SUITES = [
  "src/services/admin.rows.test.ts",
  "src/services/admin.schema.test.ts",
  "src/services/admin.selector.test.ts",
];

/**
 * The database tests' settings (TEST_DATABASE_*) from `.env`, so `pnpm test:db`
 * finds the local database. Only these: nothing else in `.env` (DATABASE_URL
 * above all) reaches a test run. The shell's values win.
 */
function testDatabaseEnv(): Record<string, string> {
  const file = existsSync(".env") ? parse(readFileSync(".env")) : {};
  return Object.fromEntries(
    Object.entries(file).filter(
      ([name]) => name.startsWith("TEST_DATABASE_") && process.env[name] === undefined,
    ),
  );
}

const testDatabase = testDatabaseEnv();
const testDatabaseUrl = process.env.TEST_DATABASE_URL ?? testDatabase.TEST_DATABASE_URL;

/**
 * With a test database, the database project runs the Admin suites too, over
 * the database arm: the seams' DATABASE_URL is the test database, never the
 * shell's or .env's. Without one, it runs only the `*.db.test.ts` files, which
 * skip saying why.
 */
const adminSuitesOnDatabase = testDatabaseUrl
  ? {
      include: [DATABASE_TESTS, ADMIN_SUITES],
      exclude: [...configDefaults.exclude, ...NOT_ADMIN_SUITES],
      env: { ...testDatabase, DATABASE_URL: testDatabaseUrl, ADMIN_TEST_ARM: "database" },
    }
  : { include: [DATABASE_TESTS], env: testDatabase };

export default defineConfig({
  plugins: [react()],
  test: {
    globals: true,
    // `pnpm test` runs both projects; the database tests skip, saying why,
    // without TEST_DATABASE_URL. `pnpm test:db` runs the database ones alone.
    projects: [
      {
        extends: true,
        test: {
          name: "unit",
          environment: "jsdom",
          setupFiles: ["./vitest.setup.ts"],
          include: ["src/**/*.{test,spec}.{ts,tsx}"],
          exclude: [...configDefaults.exclude, DATABASE_TESTS],
        },
      },
      {
        extends: true,
        test: {
          name: "db",
          environment: "node",
          setupFiles: ["./vitest.setup.ts"],
          ...adminSuitesOnDatabase,
          // The files share one database and replace its catalogue: one at a time.
          poolOptions: { forks: { singleFork: true } },
        },
      },
    ],
    coverage: {
      provider: "v8",
      reporter: ["text", "lcov"],
      include: ["src/**/*.{ts,tsx}"],
      exclude: [
        "src/**/*.{test,spec}.{ts,tsx}",
        "src/components/ui/**", // vendored shadcn/ui components
        "src/lib/supabase/database.types.ts", // generated by supabase gen types
        // Drizzle DB layer: its query bodies only run against a live Postgres,
        // so the database tests (`pnpm test:db`) check them, not coverage.
        "src/lib/db/client.ts",
        "src/services/*.db.ts",
        "**/*.d.ts",
        // The seams' type-only modules (catalogue.types.ts, admin.types.ts):
        // like .d.ts files they compile to nothing, so v8 would count every
        // line as uncovered code.
        "src/**/*.types.ts",
        "**/*.config.*",
        "e2e/**",
      ],
      // Coverage ratchet: thresholds sit just below the measured baseline
      // (2026-10, after the template cleanup) so a regression fails CI, without
      // inventing numbers that fail today. src/lib is lower than the rest
      // because its Supabase clients, auth helpers and server analytics only
      // run against a live backend.
      thresholds: {
        // Global floor. Measured: 77.47% lines/statements, 78.8% functions, 89.82% branches.
        lines: 76,
        statements: 76,
        functions: 77,
        branches: 88,
        // Measured: 58.44% lines/statements, 75% functions, 90.25% branches.
        "src/lib/**": { lines: 57, statements: 57, functions: 74, branches: 89 },
        // Measured: 86.42% lines/statements, 97.91% functions, 96.41% branches.
        "src/services/**": { lines: 85, statements: 85, functions: 96, branches: 95 },
      },
    },
  },
  resolve: {
    alias: {
      "@": fileURLToPath(new URL("./src", import.meta.url)),
      // The real `server-only` package throws unless resolved with React's
      // `react-server` export condition (Next applies it; Vitest does not).
      // Stub it so server modules can be imported and unit-tested. The boundary
      // is still enforced by the real package in `next build`.
      "server-only": fileURLToPath(new URL("./test/stubs/server-only.ts", import.meta.url)),
    },
  },
});
