/** Self-hosted photos at public/products/{slug}/{n}.webp, cover first. */
function photos(slug: string, title: string, count: number): ProductPhoto[] {
  return Array.from({ length: count }, (_, index) => ({
    src: `/products/${slug}/${index + 1}.webp`,
    alt: `${title}, photo ${index + 1} of ${count}`,
  }));
}

