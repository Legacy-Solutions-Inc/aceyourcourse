// @vitest-environment node
import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import * as prettier from "prettier";
import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { convertSpreadsheet } from "./build";
import { HAND_MAINTAINED, spreadsheet } from "../../../test/fixtures/catalogue-import";
import { renderSeedModule, SEED_MODULE_PATH, writeSeedModule } from "./write";

// The generated seed module: the spreadsheet's Exams, Products and Reviews as
// typed arrays, formatted as Prettier would format them, under a header saying
// it is generated.

const { catalogue } = convertSpreadsheet(
  spreadsheet((sheets) => {
    // Quotes, curly quotes, line breaks and emoji must all survive the round trip.
    sheets.reviews[0] = {
      ...sheets.reviews[0],
      text: 'Says "10/10" and it’s true.\nSuper LEGIT 👌❤️.',
    };
  }),
  HAND_MAINTAINED,
);

let root: string;
beforeEach(async () => {
  root = await mkdtemp(join(tmpdir(), "ayc-seed-"));
});
afterEach(async () => {
  await rm(root, { recursive: true, force: true });
});

describe("renderSeedModule", () => {
  it("starts with the generated-file header and exports typed arrays", async () => {
    const source = await renderSeedModule(catalogue);

    expect(
      source.startsWith("// Generated by pnpm catalogue:import — do not edit by hand.\n"),
    ).toBe(true);
    expect(source).toContain(
      'import type { Exam, Product, Review } from "@/services/catalogue.types";',
    );
    expect(source).toContain("export const exams: Exam[] = [");
    expect(source).toContain("export const products: Product[] = [");
    expect(source).toContain("export const reviews: Review[] = [");
  });

  it("is already formatted with the repo's Prettier config", async () => {
    const source = await renderSeedModule(catalogue);
    const config = await prettier.resolveConfig(SEED_MODULE_PATH);

    expect(await prettier.format(source, { ...config, filepath: SEED_MODULE_PATH })).toBe(source);
  });

  it("holds exactly the catalogue it was given", async () => {
    const file = join(root, "catalogue.generated.ts");
    await writeSeedModule(catalogue, file);

    const generated: unknown = await import(/* @vite-ignore */ file);

    expect(generated).toEqual(expect.objectContaining(catalogue));
    expect(await readFile(file, "utf8")).toBe(await renderSeedModule(catalogue));
  });
});
