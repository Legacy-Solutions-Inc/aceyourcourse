import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

import * as prettier from "prettier";

import type { GeneratedCatalogue } from "./build";

// ─────────────────────────────────────────────────────────────────────────────
// Writes the seed module the mock Catalogue reads: the spreadsheet's Exams,
// Products and Reviews as typed arrays. It is formatted with the repo's
// Prettier config, so formatting it again (lint-staged does) changes nothing,
// and importing the same spreadsheet twice gives the same file.
// ─────────────────────────────────────────────────────────────────────────────

/** Where the mock Catalogue imports the generated seed from. */
export const SEED_MODULE_PATH = fileURLToPath(
  new URL("../../services/mock/catalogue.generated.ts", import.meta.url),
);

const HEADER = `// Generated by pnpm catalogue:import — do not edit by hand.
// Edit the catalogue spreadsheet (see data/catalogue/template/README.md) and run the import again.`;

/** The seed module's source, formatted. */
export async function renderSeedModule(catalogue: GeneratedCatalogue): Promise<string> {
  const source = [
    HEADER,
    'import type { Exam, Product, Review } from "@/services/catalogue.types";',
    `export const exams: Exam[] = ${JSON.stringify(catalogue.exams)};`,
    `export const products: Product[] = ${JSON.stringify(catalogue.products)};`,
    `export const reviews: Review[] = ${JSON.stringify(catalogue.reviews)};`,
  ].join("\n\n");
  // The config of the real module's place, wherever this copy is written.
  const config = await prettier.resolveConfig(SEED_MODULE_PATH);
  return prettier.format(source, { ...config, filepath: SEED_MODULE_PATH });
}

/** Writes the seed module, by default to the place the mock Catalogue imports it from. */
export async function writeSeedModule(
  catalogue: GeneratedCatalogue,
  path: string = SEED_MODULE_PATH,
): Promise<void> {
  await writeFile(path, await renderSeedModule(catalogue));
}
